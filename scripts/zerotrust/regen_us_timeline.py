"""Regenerate frontend/src/data/usHealthcareTimeline.ts from canonical store.

Mirrors regen_oncology.py for the US Healthcare Timeline. Reads the CSV
intermediate (or — once oncology-style migration completes — the JSON
from from_airtable.py) and reverse-maps Entity/Claim/Source back to the
USEvent shape:

  id     = tag `event_id:<...>`
  year   = floor(period_year)
  date   = period (ISO YYYY-MM-DD when known)
  era    = tag `era:<id>`
  type   = tag `type:<usevent_type>` OR reverse predicate map
  title  = first half of claim.value (before ' — ')
  why    = second half of claim.value (after ' — ')
  detail = claim.notes (lossless after schema_patch v2)
  src    = first source URL
"""
from __future__ import annotations

import argparse
import csv
import json
import os
import re
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
# Override with ZEROTRUST_DATA_DIR so this runs on any contributor's machine,
# not just the maintainer's local disk. Default preserves the legacy path.
CSV_DIR = Path(os.environ.get("ZEROTRUST_DATA_DIR") or r"C:\Projects\data\aiatls\zerotrust")
OUT_TS = REPO_ROOT / "frontend" / "src" / "data" / "usHealthcareTimeline.regenerated.ts"


def parse_tag(tags_csv: str, key: str) -> str:
    for raw in tags_csv.split(","):
        raw = raw.strip()
        if raw.startswith(f"{key}:"):
            return raw[len(key) + 1:].strip()
    return ""


def parse_year(period: str) -> int:
    m = re.match(r"^(\d{4})", (period or "").strip())
    return int(m.group(1)) if m else 0


def load_csv(name: str) -> list[dict]:
    p = CSV_DIR / name
    if not p.exists():
        print(f"ERROR: {p} not found — run extract_us_timeline --write first.", file=sys.stderr)
        sys.exit(2)
    with open(p, encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def regen() -> str:
    claims = load_csv("claims_us_timeline.csv")
    sources_by_id = {s["source_id"]: s for s in load_csv("sources_us_timeline.csv")}

    events: list[dict] = []
    for c in claims:
        tags = c.get("tags") or ""
        period = c.get("period") or ""
        year = parse_year(period)
        date_iso = period if re.match(r"^\d{4}-\d{2}-\d{2}$", period) else ""

        # claim.value was set as: f"{title} — {ev.get('why', '')}"
        full_value = (c.get("value") or "").strip()
        # Split on em-dash with surrounding spaces
        if " — " in full_value:
            title, why = full_value.split(" — ", 1)
        else:
            title, why = full_value, ""

        sid = (c.get("source_ids") or "").split(",")[0].strip()
        src = sources_by_id.get(sid, {}).get("url", "")

        event = {
            "id": parse_tag(tags, "event_id") or "",
            "year": year,
            "date": date_iso or None,
            "era": parse_tag(tags, "era") or "",
            "type": parse_tag(tags, "type") or "",
            "title": title.strip(),
            "why": why.strip(),
            "detail": (c.get("notes") or "").strip(),
            "src": src,
        }
        events.append(event)

    events.sort(key=lambda e: (e["year"], e["id"]))

    out = [
        "// AUTO-GENERATED by scripts/zerotrust/regen_us_timeline.py",
        "// Source of truth: Airtable (via zerotrust). CSV intermediate used in this PoC run.",
        f"// Events: {len(events)}",
        "//",
        "// Round-trip fidelity: LOSSLESS for title / why / detail / src once",
        "// the Notes field is in place (schema_patch v2). The era/type vocabulary",
        "// is preserved verbatim via tags.",
        "",
        "import type { USEvent } from './usHealthcareTimeline';",
        "",
        f"export const US_TIMELINE_REGEN: USEvent[] = {json.dumps(events, indent=2, ensure_ascii=False)};",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    ts = regen()
    if args.write:
        OUT_TS.parent.mkdir(parents=True, exist_ok=True)
        OUT_TS.write_text(ts, encoding="utf-8")
        print(f"Wrote {OUT_TS.relative_to(REPO_ROOT)} ({len(ts)} chars)", file=sys.stderr)
    else:
        sys.stdout.write(ts)
    return 0


if __name__ == "__main__":
    sys.exit(main())

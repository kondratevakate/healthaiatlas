// Invariants for the generated biosecurity dataset. biosecurity.ts is written
// by scripts/zerotrust/regen_biosecurity.py — these checks catch a hand edit
// or a regen bug before it reaches the hub views.

import { readFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

import { describe, it, expect } from 'vitest';

import { BIO_COLUMNS, BIO_FOCUS_ORDER, BIO_GROUPS, BIO_ORGS, BIO_SOURCE } from '../biosecurity';

const __dirname = dirname(fileURLToPath(import.meta.url));
const DATA_FILE = resolve(__dirname, '../biosecurity.ts');

describe('biosecurity dataset integrity', () => {
  it('is generated, not hand-written', () => {
    expect(readFileSync(DATA_FILE, 'utf8').split('\n')[0]).toContain('AUTO-GENERATED by scripts/zerotrust/regen_biosecurity.py');
  });

  it('has a plausible number of organisations with unique ids', () => {
    expect(BIO_ORGS.length).toBeGreaterThan(100);
    expect(new Set(BIO_ORGS.map((o) => o.id)).size).toBe(BIO_ORGS.length);
  });

  it('every organisation is filed under at least one known column', () => {
    const columnIds = new Set(BIO_COLUMNS.map((c) => c.id));
    const offenders = BIO_ORGS.filter((o) => o.cols.length === 0 || o.cols.some((c) => !columnIds.has(c)));
    expect(offenders.map((o) => o.id)).toEqual([]);
  });

  it('every column belongs to a declared group with a colour', () => {
    const groups = new Map(BIO_GROUPS.map((g) => [g.id, g]));
    expect(BIO_COLUMNS.filter((c) => !groups.get(c.group)?.color).map((c) => c.id)).toEqual([]);
  });

  it('focus values are drawn from BIO_FOCUS_ORDER and exclude approach tags', () => {
    const order = new Set(BIO_FOCUS_ORDER);
    const offenders = BIO_ORGS.flatMap((o) => o.focus.filter((f) => !order.has(f) || f.startsWith('[')));
    expect(offenders).toEqual([]);
  });

  // AGENTS.md hard rule 1: only URLs read from upstream. Every categorisation
  // claim cites the directory view; per-row Notion URLs are never constructed.
  it('every organisation cites the directory as its source', () => {
    expect(BIO_ORGS.filter((o) => o.src !== BIO_SOURCE.url).map((o) => o.id)).toEqual([]);
    const notionUrls = readFileSync(DATA_FILE, 'utf8').match(/https?:\/\/[^"\s]*notion\.site[^"\s]*/g) ?? [];
    expect(new Set(notionUrls)).toEqual(new Set([BIO_SOURCE.url]));
  });

  it('websites are absolute http(s) URLs or empty', () => {
    expect(BIO_ORGS.filter((o) => o.web && !/^https?:\/\//.test(o.web)).map((o) => o.id)).toEqual([]);
  });
});

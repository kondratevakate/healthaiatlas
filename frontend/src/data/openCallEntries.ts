// Open Calls — unified card-grid feed.
//
// Replaces the prior split between grants.ts / programs.ts / openCalls.ts. Every
// entry below is an application-window call (grant, fellowship, accelerator,
// prize, regulatory sandbox). Investors, societies, conferences, and standing
// research orgs are out of scope here — they belong in their own places (or in
// a future Investors view) rather than diluting the calls list.
//
// Compliance: every entry must include a primary `url` on the issuer's domain.
// Quantitative facts (amounts, deadlines, audience size) are kept verbatim from
// the source they were drawn from — the curated Europe_VS funds spreadsheet
// (verifiedAt: 2026-05-06) for ~33 entries, and prior site scaffolds for the
// rest. `verifiedAt` is set when the source URL was spot-checked; un-stamped
// entries inherit the prior scaffold's TODO state.

export type GrantRegion = 'US' | 'EU' | 'UK' | 'UAE' | 'Global';

export type OpenCallCategory =
  | 'grant'        // Mega-Funder grants, govt research grants, RFPs
  | 'fellowship'   // Named fellowships, residencies
  | 'accelerator'  // Cohort-based accelerators / incubators
  | 'prize'        // Prize competitions, hiring contests
  | 'sandbox'      // Regulatory sandboxes, pilot calls
  | 'hackathon';   // Time-bound coding/clinical-data competitions (Kaggle, NHS, MIT, etc.)

export type CountdownStatus =
  | { kind: 'deadline'; date: Date }
  | { kind: 'rolling' }
  | { kind: 'annual'; nextWindow?: string }
  | { kind: 'closed'; nextExpected?: string };

export interface OpenCallEntry {
  id: string;
  title: string;
  organizer: string;
  url: string;
  region: GrantRegion;
  category: OpenCallCategory;
  countdown: CountdownStatus;
  amount?: string;
  audience?: string;
  notes?: string;
  verifiedAt?: string; // ISO date, set when URL + facts last spot-checked
}

